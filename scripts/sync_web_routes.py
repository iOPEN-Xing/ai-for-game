"""Generate the team and player browser route tables from the ASGI OpenAPI document."""

import argparse
import json
import re

from app import app
from studio.settings import WEB

PLAYER_ROUTES = {
    "public_cartridge",
    "player_page",
    "sample",
    "visit_activity",
    "open_round",
    "show_hint",
    "event",
    "feedback",
}


def endpoints() -> dict[str, str]:
    result = {}
    for path, methods in app.openapi()["paths"].items():
        for verb, operation in methods.items():
            identifier = operation["operationId"]
            suffix = re.sub(r"\W", "_", path) + "_" + verb
            if not identifier.endswith(suffix):
                raise ValueError(f"Unexpected operation identifier {identifier}")
            name = identifier.removesuffix(suffix)
            if name in result:
                raise ValueError(f"Duplicate operation name {name}")
            result[name] = path
    return result


def render(routes: dict[str, str]) -> str:
    return (
        "// Generated by python -m scripts.sync_web_routes\n"
        "import { pathFor } from './api-client.js';\n\n"
        "const paths = Object.freeze("
        + json.dumps(routes, sort_keys=True, indent=2)
        + ");\n\nexport const endpoint = (name, parameters, query) => pathFor(paths, name, parameters, query);\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    routes = endpoints()
    for name, entries in (
        ("routes.js", routes),
        ("player-routes.js", {key: routes[key] for key in PLAYER_ROUTES}),
    ):
        path = WEB / name
        expected = render(entries)
        if args.check:
            if not path.exists() or path.read_text() != expected:
                parser.exit(
                    1,
                    f"{name} differs from OpenAPI. Run python -m scripts.sync_web_routes.\n",
                )
        else:
            path.write_text(expected)


if __name__ == "__main__":
    main()

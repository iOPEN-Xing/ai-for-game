CREATE TABLE IF NOT EXISTS games(id TEXT PRIMARY KEY,title TEXT NOT NULL,brief TEXT NOT NULL,
  metric TEXT NOT NULL,bounds TEXT NOT NULL,live TEXT,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS revisions(id TEXT PRIMARY KEY,game TEXT NOT NULL REFERENCES games(id),
  num INTEGER NOT NULL,stage TEXT NOT NULL,serial INTEGER NOT NULL DEFAULT 0,
  seed INTEGER NOT NULL,parent TEXT,proposal TEXT,choice INTEGER,notes TEXT NOT NULL DEFAULT '',
  docs TEXT NOT NULL DEFAULT '{}',bundle TEXT,created INTEGER NOT NULL,UNIQUE(game,num));
CREATE TABLE IF NOT EXISTS history(id INTEGER PRIMARY KEY,game TEXT,rev TEXT,role TEXT NOT NULL,
  text TEXT NOT NULL,kind TEXT NOT NULL,at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS history_rev ON history(rev,id);
CREATE TABLE IF NOT EXISTS jobs(id TEXT PRIMARY KEY,kind TEXT NOT NULL,target TEXT NOT NULL,
  stage TEXT NOT NULL,state TEXT NOT NULL,attempts INTEGER NOT NULL DEFAULT 0,
  heartbeat INTEGER NOT NULL DEFAULT 0,error TEXT,created INTEGER NOT NULL,UNIQUE(kind,target,stage));
CREATE TABLE IF NOT EXISTS proposals(id TEXT PRIMARY KEY,game TEXT REFERENCES games(id),
  base TEXT NOT NULL,kind TEXT NOT NULL,day TEXT NOT NULL,status TEXT NOT NULL,doc TEXT NOT NULL DEFAULT '{}',
  evidence TEXT NOT NULL,created INTEGER NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS proposal_batch ON proposals(game,day,kind);
CREATE TABLE IF NOT EXISTS experiments(id TEXT PRIMARY KEY,game TEXT NOT NULL REFERENCES games(id),
  proposal TEXT NOT NULL UNIQUE REFERENCES proposals(id),control TEXT NOT NULL,treatment TEXT NOT NULL,
  started INTEGER NOT NULL,due INTEGER NOT NULL,status TEXT NOT NULL,result TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS experiment_active ON experiments(game) WHERE status IN ('running','decide');
CREATE TABLE IF NOT EXISTS rounds(id TEXT PRIMARY KEY,game TEXT NOT NULL,rev TEXT NOT NULL,
  player TEXT NOT NULL,level INTEGER NOT NULL,preview INTEGER NOT NULL,experiment TEXT,arm TEXT,
  bundle TEXT NOT NULL,issued INTEGER NOT NULL,started INTEGER,ended INTEGER,won INTEGER,score INTEGER);
CREATE INDEX IF NOT EXISTS rounds_report ON rounds(game,preview,started);
CREATE INDEX IF NOT EXISTS rounds_experiment ON rounds(experiment,arm);
CREATE INDEX IF NOT EXISTS published_bundles ON revisions(bundle) WHERE stage='released';
CREATE TABLE IF NOT EXISTS feedback(id TEXT PRIMARY KEY,round TEXT UNIQUE NOT NULL REFERENCES rounds(id),
  rating INTEGER NOT NULL,comment TEXT NOT NULL,at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS knowledge(id TEXT PRIMARY KEY,game TEXT NOT NULL,experiment TEXT NOT NULL,
  text TEXT NOT NULL,evidence TEXT NOT NULL,grade TEXT NOT NULL,status TEXT NOT NULL,
  confidence REAL NOT NULL,previous TEXT,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS game_requests(request_id TEXT PRIMARY KEY,fingerprint TEXT NOT NULL,game TEXT NOT NULL,rev TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS external_changes(id TEXT PRIMARY KEY,game TEXT NOT NULL REFERENCES games(id),
  text TEXT NOT NULL,affects_measurement INTEGER NOT NULL,at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS batches(day TEXT PRIMARY KEY,status TEXT NOT NULL,doc TEXT NOT NULL,at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS preferences(scope TEXT NOT NULL,subject TEXT NOT NULL,version INTEGER NOT NULL,settings TEXT NOT NULL,PRIMARY KEY(scope,subject));
CREATE TABLE IF NOT EXISTS skill_revisions(name TEXT NOT NULL,revision TEXT NOT NULL,description TEXT NOT NULL,body TEXT NOT NULL,PRIMARY KEY(name,revision));
CREATE TABLE IF NOT EXISTS agent_runs(id TEXT PRIMARY KEY,model TEXT NOT NULL,manifest TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS agent_prompts(run TEXT NOT NULL REFERENCES agent_runs(id),role TEXT NOT NULL,node TEXT NOT NULL,schema_hash TEXT NOT NULL,prompt TEXT NOT NULL,PRIMARY KEY(run,role,node));
CREATE TABLE IF NOT EXISTS agent_inputs(run TEXT NOT NULL REFERENCES agent_runs(id),node TEXT NOT NULL,context_hash TEXT NOT NULL,
  payload BLOB NOT NULL,created INTEGER NOT NULL,PRIMARY KEY(run,node,context_hash));
CREATE TABLE IF NOT EXISTS reference_blobs(digest TEXT PRIMARY KEY,content BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS reference_selections(run TEXT NOT NULL REFERENCES agent_runs(id),ref TEXT NOT NULL,
  digest TEXT NOT NULL REFERENCES reference_blobs(digest),PRIMARY KEY(run,ref));
CREATE TABLE IF NOT EXISTS revision_progress(rev TEXT PRIMARY KEY,scope TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS experiment_progress(experiment TEXT PRIMARY KEY,scope TEXT NOT NULL,policy TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS proposal_history(id INTEGER PRIMARY KEY,proposal TEXT NOT NULL,evidence TEXT NOT NULL,doc TEXT NOT NULL,reason TEXT NOT NULL,at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS campaigns(id TEXT PRIMARY KEY,game TEXT NOT NULL REFERENCES games(id),
  name TEXT NOT NULL,action_label TEXT,action_url TEXT,created INTEGER NOT NULL,UNIQUE(game,name));
